def pick(node, i):
    if isinstance(node, tuple): return node[i]
    return {k: pick(v, i) for k, v in node.items()}

with open(os.path.join(ROOT, 'scripts', 'i18n-nl-de.json'), encoding='utf-8') as f:
    NL_DE = json.load(f)  # { anglais: [nl, de] }
MISSING = set()


def pick_nl_de(node, j):
    """nl (j=0) ou de (j=1) depuis i18n-nl-de.json, indexé par le texte anglais ; repli sur l'anglais."""
    if isinstance(node, tuple):
        tr = NL_DE.get(node[1])
        if tr is None:
            MISSING.add(node[1])
            return node[1]
        return tr[j]
    return {k: pick_nl_de(v, j) for k, v in node.items()}


